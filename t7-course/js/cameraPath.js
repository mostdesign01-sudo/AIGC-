const posKeys = KEYS.map(k => new THREE.Vector3(...k.pos));
const lookKeys = KEYS.map(k => new THREE.Vector3(...k.look));
const tKeys = KEYS.map(k => k.t);

/* 分段 Catmull-Rom（非均匀关键帧时间） */
function sampleCR(points, i0, s, out) {
  const n = points.length;
  const p0 = points[Math.max(0, i0 - 1)];
  const p1 = points[i0];
  const p2 = points[Math.min(n - 1, i0 + 1)];
  const p3 = points[Math.min(n - 1, i0 + 2)];
  const s2 = s * s, s3 = s2 * s;
  out.set(
    0.5 * ((2 * p1.x) + (-p0.x + p2.x) * s + (2 * p0.x - 5 * p1.x + 4 * p2.x - p3.x) * s2 + (-p0.x + 3 * p1.x - 3 * p2.x + p3.x) * s3),
    0.5 * ((2 * p1.y) + (-p0.y + p2.y) * s + (2 * p0.y - 5 * p1.y + 4 * p2.y - p3.y) * s2 + (-p0.y + 3 * p1.y - 3 * p2.y + p3.y) * s3),
    0.5 * ((2 * p1.z) + (-p0.z + p2.z) * s + (2 * p0.z - 5 * p1.z + 4 * p2.z - p3.z) * s2 + (-p0.z + 3 * p1.z - 3 * p2.z + p3.z) * s3)
  );
  return out;
}

export function samplePath(t, outPos, outLook) {
  const p = Math.min(1, Math.max(0, t));
  let i = 0;
  while (i < tKeys.length - 2 && p >= tKeys[i + 1]) i++;
  const s = (p - tKeys[i]) / (tKeys[i + 1] - tKeys[i]);
  const cs = Math.min(1, Math.max(0, s));
  sampleCR(posKeys, i, cs, outPos);
  sampleCR(lookKeys, i, cs, outLook);
}

export function windowSpan(p, win) {
  return Math.min(1, Math.max(0, (p - win[0]) / (win[1] - win[0])));
}
